#!/usr/bin/env bash
# ./deltactl completion bash: prints the bash completion (Tab) for ./deltactl.
# It completes commands, instances, services, options, help topics and glossary variables.
#
# Enable it in the current session:   source <(./deltactl completion bash)
# Keep it permanently (once):         ./deltactl completion bash > ~/.deltactl-completion.bash
#                                     echo 'source ~/.deltactl-completion.bash' >> ~/.bashrc
# Command, topic, service and variable names are taken from the code itself when the script is
# generated, so they never go stale; instances are read on every Tab.

# help.sh provides HELP_COMMANDS and HELP_TOPICS
source "$ROOT/lib/cmd/help.sh"

# Options of each command (tests/test-completion.sh checks that they appear on its help page).
COMPLETION_FLAGS=(
  "new:--services --existing --wizard"
  "init:--yes"
  "rollback:--yes"
  "down:--yes"
  "status:--json --stats --strict --watch"
  "images:--json"
  "versions:--json"
  "check:--mongo"
  "logs:-f"
  "menu:--classic"
)

cmd_completion() {
  local shell="${1:-}" tmpl flags f vars
  [ -n "$shell" ] || die "$(t completion.usage)"
  [ "$shell" = "bash" ] || die "$(t completion.only_bash "$shell")"

  flags=""
  for f in "${COMPLETION_FLAGS[@]}"; do flags+="    ${f%%:*}) flags=\"${f#*:}\" ;;"$'\n'; done
  vars="$(grep -E '^@ ' "$ROOT/lib/help/variables.txt" | sed 's/^@ //; s/ .*//' | sort -u | tr '\n' ' ')"

  IFS= read -r -d '' tmpl <<'EOF' || true
# deltactl: bash completion (generated by ./deltactl completion bash)
_deltactl_complete() {
  local cur="${COMP_WORDS[COMP_CWORD]}" cmd="${COMP_WORDS[1]:-}" prev="${COMP_WORDS[COMP_CWORD-1]}"
  local cmds="@COMMANDS@" topics="@TOPICS@" services="@SERVICES@" vars="@VARS@"
  local insts="" f flags=""
  for f in "@ROOT@"/instances/*/.env.instance; do
    [ -f "$f" ] && insts+="$(basename "$(dirname "$f")") "
  done
  COMPREPLY=()

  if [ "$COMP_CWORD" -eq 1 ]; then
    COMPREPLY=($(compgen -W "$cmds menu completion" -- "$cur"))
    return 0
  fi

  case "$cmd" in
@FLAGS@  esac
  if [[ "$cur" == -* ]]; then
    COMPREPLY=($(compgen -W "$flags" -- "$cur"))
    return 0
  fi

  case "$cmd" in
    help)
      if [ "$prev" = "variable" ] || [ "$prev" = "variables" ]; then
        COMPREPLY=($(compgen -W "$vars" -- "$cur"))
      elif [ "$COMP_CWORD" -eq 2 ]; then
        COMPREPLY=($(compgen -W "$cmds $topics variable buscar temas" -- "$cur"))
      fi ;;
    deploy | rollback | stop | logs | check | status)
      if [ "$COMP_CWORD" -eq 2 ]; then COMPREPLY=($(compgen -W "$insts" -- "$cur"))
      elif [ "$COMP_CWORD" -eq 3 ]; then COMPREPLY=($(compgen -W "$services" -- "$cur")); fi ;;
    init | adopt | down | ps)
      [ "$COMP_CWORD" -eq 2 ] && COMPREPLY=($(compgen -W "$insts" -- "$cur")) ;;
    images | versions)
      [ "$COMP_CWORD" -eq 2 ] && COMPREPLY=($(compgen -W "$services" -- "$cur")) ;;
    load)
      COMPREPLY=($(compgen -f -- "$cur")) ;;
    completion)
      [ "$COMP_CWORD" -eq 2 ] && COMPREPLY=($(compgen -W "bash" -- "$cur")) ;;
  esac
  return 0
}
complete -F _deltactl_complete deltactl ./deltactl "@ROOT@/deltactl"
EOF
  tmpl="${tmpl//@COMMANDS@/${HELP_COMMANDS[*]}}"
  tmpl="${tmpl//@TOPICS@/${HELP_TOPICS[*]}}"
  tmpl="${tmpl//@SERVICES@/${KNOWN_SERVICES[*]}}"
  tmpl="${tmpl//@VARS@/$vars}"
  tmpl="${tmpl//@ROOT@/$ROOT}"
  tmpl="${tmpl//@FLAGS@/$flags}"
  printf '%s\n' "$tmpl"
}
